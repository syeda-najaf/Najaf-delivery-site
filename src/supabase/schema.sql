create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null default 'Home',
  address_text text not null,
  city text default 'Bengaluru',
  state text default 'Karnataka',
  country text default 'India',
  pincode text,
  lat double precision,
  lng double precision,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  id integer primary key,
  name text not null,
  category text not null,
  price integer not null check (price >= 0),
  rating numeric(2,1),
  prep_minutes integer default 20,
  image_url text,
  description text,
  active boolean not null default true
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'payment_pending',
  payment_status text not null default 'pending',
  subtotal integer not null,
  delivery_fee integer not null default 0,
  total integer not null,
  razorpay_order_id text unique,
  razorpay_payment_id text,
  address_id uuid references public.addresses(id) on delete set null,
  address_snapshot jsonb not null default '{}'::jsonb,
  destination_lat double precision,
  destination_lng double precision,
  rider_name text default 'Ayaan',
  rider_phone text,
  rider_lat double precision,
  rider_lng double precision,
  rider_heading double precision,
  eta_minutes integer,
  status_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  menu_item_id integer references public.menu_items(id) on delete restrict,
  name text not null,
  unit_price integer not null,
  quantity integer not null check (quantity > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  event_type text not null,
  message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

